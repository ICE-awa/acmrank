CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username CITEXT NOT NULL,
  email CITEXT NOT NULL,
  real_name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending_verification' CHECK (status IN ('pending_verification', 'active', 'disabled')),
  email_verified_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (username),
  UNIQUE (email)
);

CREATE TABLE platform_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  platform TEXT NOT NULL CHECK (platform IN ('codeforces', 'atcoder', 'luogu')),
  handle CITEXT NOT NULL,
  display_handle TEXT,
  status TEXT NOT NULL DEFAULT 'pending_review' CHECK (status IN ('pending_review', 'verified', 'disabled', 'rejected')),
  verified_at TIMESTAMPTZ,
  last_synced_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (platform, handle)
);

CREATE TABLE platform_account_reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  platform_account_id BIGINT NOT NULL REFERENCES platform_accounts (id) ON DELETE CASCADE,
  reviewer_user_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
  from_status TEXT,
  to_status TEXT NOT NULL CHECK (to_status IN ('pending_review', 'verified', 'disabled', 'rejected')),
  reason TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE sync_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_user_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
  platform_account_id BIGINT REFERENCES platform_accounts (id) ON DELETE SET NULL,
  platform TEXT CHECK (platform IS NULL OR platform IN ('codeforces', 'atcoder', 'luogu', 'icpc', 'clist')),
  job_type TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('queued', 'running', 'succeeded', 'failed', 'cancelled')),
  scheduled_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  started_at TIMESTAMPTZ,
  finished_at TIMESTAMPTZ,
  attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  error_message TEXT,
  payload JSONB NOT NULL DEFAULT '{}'::JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE platform_profile_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  platform_account_id BIGINT NOT NULL REFERENCES platform_accounts (id) ON DELETE CASCADE,
  source TEXT NOT NULL,
  display_name TEXT,
  rating INTEGER,
  max_rating INTEGER,
  profile_url TEXT,
  raw_payload_ref TEXT,
  payload JSONB NOT NULL DEFAULT '{}'::JSONB,
  fetched_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE accepted_event_raw (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_user_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
  platform_account_id BIGINT REFERENCES platform_accounts (id) ON DELETE SET NULL,
  platform TEXT NOT NULL CHECK (platform IN ('codeforces', 'atcoder', 'luogu')),
  handle CITEXT NOT NULL,
  problem_key TEXT NOT NULL,
  contest_id TEXT,
  problem_index_or_task_id TEXT,
  problem_name TEXT,
  problem_url TEXT,
  accepted_at TIMESTAMPTZ NOT NULL,
  submission_id_or_ref TEXT,
  source TEXT NOT NULL,
  source_url TEXT,
  raw_payload_ref TEXT,
  payload JSONB NOT NULL DEFAULT '{}'::JSONB,
  fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE problem_facts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  platform TEXT NOT NULL CHECK (platform IN ('codeforces', 'atcoder', 'luogu')),
  problem_key TEXT NOT NULL,
  contest_id TEXT,
  problem_index_or_task_id TEXT,
  problem_name TEXT,
  problem_url TEXT,
  first_ac_at TIMESTAMPTZ NOT NULL,
  first_ac_source TEXT NOT NULL,
  first_ac_submission_ref TEXT,
  first_ac_event_raw_id BIGINT REFERENCES accepted_event_raw (id) ON DELETE SET NULL,
  latest_ac_at TIMESTAMPTZ NOT NULL,
  clist_problem_id BIGINT,
  clist_contest_id BIGINT,
  clist_rating INTEGER,
  metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (first_ac_at <= latest_ac_at),
  UNIQUE (site_user_id, platform, problem_key)
);

CREATE TABLE contest_ac_summaries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  platform TEXT NOT NULL CHECK (platform IN ('codeforces', 'atcoder', 'luogu')),
  contest_id TEXT NOT NULL,
  contest_name TEXT,
  ac_problem_keys TEXT[] NOT NULL DEFAULT '{}'::TEXT[],
  ac_count INTEGER NOT NULL DEFAULT 0 CHECK (ac_count >= 0),
  first_ac_at TIMESTAMPTZ,
  last_ac_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (site_user_id, platform, contest_id)
);

CREATE TABLE award_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  platform TEXT NOT NULL DEFAULT 'icpc' CHECK (platform = 'icpc'),
  contest_name TEXT NOT NULL,
  award_name TEXT NOT NULL,
  rank_text TEXT,
  award_date DATE NOT NULL,
  source TEXT NOT NULL,
  source_url TEXT,
  is_manual BOOLEAN NOT NULL DEFAULT FALSE,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (site_user_id, platform, contest_name, award_name, award_date)
);

CREATE TABLE clist_problem_mappings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  platform TEXT NOT NULL CHECK (platform IN ('codeforces', 'atcoder')),
  problem_key TEXT NOT NULL,
  clist_problem_id BIGINT NOT NULL,
  clist_contest_id BIGINT,
  clist_resource_id BIGINT,
  clist_resource_name TEXT,
  problem_name TEXT,
  problem_url TEXT,
  rating INTEGER,
  metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
  fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (platform, problem_key),
  UNIQUE (clist_problem_id)
);

CREATE TABLE atcoder_extension_sync_states (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  platform_account_id BIGINT NOT NULL REFERENCES platform_accounts (id) ON DELETE CASCADE,
  atcoder_handle CITEXT NOT NULL,
  last_success_synced_at TIMESTAMPTZ,
  last_attempt_synced_at TIMESTAMPTZ,
  last_extension_sync_status TEXT NOT NULL DEFAULT 'idle' CHECK (last_extension_sync_status IN ('idle', 'running', 'success', 'failed')),
  last_window_from TIMESTAMPTZ,
  last_window_to TIMESTAMPTZ,
  last_uploaded_count INTEGER NOT NULL DEFAULT 0 CHECK (last_uploaded_count >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (platform_account_id)
);

CREATE TABLE user_platform_stats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  platform TEXT NOT NULL CHECK (platform IN ('codeforces', 'atcoder', 'luogu')),
  verified_account_count INTEGER NOT NULL DEFAULT 0 CHECK (verified_account_count >= 0),
  solved_count INTEGER NOT NULL DEFAULT 0 CHECK (solved_count >= 0),
  display_rating INTEGER,
  last_aggregated_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (site_user_id, platform)
);

CREATE TABLE user_rating_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  snapshot_at TIMESTAMPTZ NOT NULL,
  at_best_score NUMERIC(10, 4) NOT NULL DEFAULT 0,
  at_recent_score NUMERIC(10, 4) NOT NULL DEFAULT 0,
  at_training_score NUMERIC(10, 4) NOT NULL DEFAULT 0,
  cf_best_score NUMERIC(10, 4) NOT NULL DEFAULT 0,
  cf_recent_score NUMERIC(10, 4) NOT NULL DEFAULT 0,
  cf_training_score NUMERIC(10, 4) NOT NULL DEFAULT 0,
  recent_score NUMERIC(10, 4) NOT NULL DEFAULT 0,
  scnu_rating NUMERIC(10, 4) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (site_user_id, snapshot_at)
);

CREATE TABLE leaderboard_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_type TEXT NOT NULL CHECK (snapshot_type IN ('daily_close', 'current')),
  snapshot_date DATE NOT NULL,
  snapshot_at TIMESTAMPTZ NOT NULL,
  site_user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  rank INTEGER NOT NULL CHECK (rank > 0),
  at_training_score NUMERIC(10, 4) NOT NULL DEFAULT 0,
  cf_training_score NUMERIC(10, 4) NOT NULL DEFAULT 0,
  recent_score NUMERIC(10, 4) NOT NULL DEFAULT 0,
  scnu_rating NUMERIC(10, 4) NOT NULL DEFAULT 0,
  today_new_accepted_count INTEGER NOT NULL DEFAULT 0 CHECK (today_new_accepted_count >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (snapshot_type, snapshot_date, site_user_id)
);

CREATE TABLE heatmap_daily_stats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  stat_date DATE NOT NULL,
  new_accepted_count INTEGER NOT NULL DEFAULT 0 CHECK (new_accepted_count >= 0),
  platform_breakdown JSONB NOT NULL DEFAULT '{}'::JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (site_user_id, stat_date)
);

